import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';

import 'app.dart';
import 'config.dart';
import 'firebase_options.dart';
import 'services/attempt_store.dart';
import 'services/fault_switches.dart';
import 'services/firebase_auth_gateway.dart';
import 'services/firestore_attempt_store.dart';
import 'services/trivia_api.dart';
import 'state/quiz_controller.dart';
import 'util/event_log.dart';

Future<void> main() async {
  // Flutter bindings must exist before any plugin is called.
  WidgetsFlutterBinding.ensureInitialized();

  try {
    // Firebase is initialized once, before the app is rendered, with the
    // options generated by `flutterfire configure`.
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );
  } catch (_) {
    runApp(const FirebaseInitErrorApp());
    return;
  }

  final log = EventLog();
  // The fault lab only exists in development builds.
  final faults = kDevTools ? FaultSwitches() : null;

  AttemptStore store = FirestoreAttemptStore();
  if (faults != null) {
    store = FaultInjectingStore(store, faults);
  }

  final controller = QuizController(
    auth: FirebaseAuthGateway(),
    api: OpenTdbApi(faults: faults),
    store: store,
    log: log,
  );
  log.add('app started build=$kGitCommit devTools=$kDevTools');

  runApp(
    QuizApp(
      deps: AppDeps(
        controller: controller,
        store: store,
        log: log,
        faults: faults,
      ),
    ),
  );
}
